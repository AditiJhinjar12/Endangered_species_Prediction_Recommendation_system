import React, { useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { FaBrain, FaFilter, FaShieldAlt, FaChartLine } from 'react-icons/fa';
import { DashboardLayout } from '../components/DashboardLayout';
import { Card } from '../components/Card';
import { speciesList } from '../data/speciesData';

export const Recommendations: React.FC = () => {
  const [searchParams, setSearchParams] = useSearchParams();
  const initialId = searchParams.get('species') || 'tiger';
  const [selectedId, setSelectedId] = useState(initialId);

  const handleSpeciesChange = (e: React.ChangeEvent<HTMLSelectElement>) => {
    const newId = e.target.value;
    setSelectedId(newId);
    setSearchParams({ species: newId });
  };

  const species = speciesList.find(s => s.id === selectedId) || speciesList[0];

  return (
    <DashboardLayout activeTabId="recommendations">
      <div className="space-y-8 text-left">
        {/* Header */}
        <div className="border-b border-emerald-950/40 pb-5">
          <h1 className="text-3xl font-extrabold tracking-tight text-white">AI Conservation Recommendations</h1>
          <p className="text-gray-500 text-xs sm:text-sm mt-1">
            Data-driven biological policies and habitat interventions generated by analyzing threat severity profiles and future population forecasts.
          </p>
        </div>

        {/* Layout Grid */}
        <div className="grid grid-cols-1 lg:grid-cols-4 gap-8 items-start">
          
          {/* Controls Panel */}
          <div className="lg:col-span-1 space-y-6">
            <Card hoverable={false} className="border-emerald-900/10 p-5 bg-[#020905]/45 backdrop-blur-md">
              <div className="space-y-5">
                <div className="flex items-center space-x-2 border-b border-emerald-950/40 pb-3">
                  <FaFilter className="text-brand-green" />
                  <h3 className="font-bold text-white text-sm">Target Species</h3>
                </div>

                <div className="space-y-1.5">
                  <label className="text-[10px] text-gray-500 uppercase tracking-wider font-semibold">Select Species</label>
                  <select
                    value={selectedId}
                    onChange={handleSpeciesChange}
                    className="block w-full px-3 py-2.5 bg-[#051109] border border-emerald-900/30 focus:border-brand-green/40 rounded-xl text-xs text-white focus:outline-none focus:ring-0"
                  >
                    {speciesList.map(s => (
                      <option key={s.id} value={s.id} className="bg-[#051109] text-white">
                        {s.commonName}
                      </option>
                    ))}
                  </select>
                </div>

                {/* Status summaries */}
                <div className="space-y-3 pt-2 text-xs">
                  <div className="flex justify-between items-center py-2 border-b border-emerald-950/30">
                    <span className="text-gray-400">Model Status</span>
                    <span className="text-brand-green font-semibold">Live Data Sync</span>
                  </div>
                  <div className="flex justify-between items-center py-2 border-b border-emerald-950/30">
                    <span className="text-gray-400">Total Indicators</span>
                    <span className="text-white font-bold font-mono">{species.threats.length} Factors</span>
                  </div>
                  <div className="flex justify-between items-center py-2">
                    <span className="text-gray-400">Dataset Records</span>
                    <span className="text-white font-bold font-mono">{species.recordsUsed} logs</span>
                  </div>
                </div>

              </div>
            </Card>
          </div>

          {/* Recommendations Content Panel */}
          <div className="lg:col-span-3 space-y-6">
            
            {/* Disclaimer Alert */}
            <div className="bg-emerald-950/20 border border-emerald-900/25 rounded-xl p-4 flex items-start space-x-3 shadow-xs text-left">
              <FaShieldAlt className="text-brand-green h-4 w-4 mt-0.5 min-w-[16px]" />
              <div className="text-xs">
                <span className="font-bold text-white uppercase block tracking-wider text-[9px] mb-1">Scientific Integrity Alert:</span>
                <p className="text-emerald-100/50 leading-relaxed">
                  The system recommends these guidelines based on biological indicators and historical correlation rules. These parameters should serve as research suggestions and should not supersede direct local zoological expertise or conservation laws.
                </p>
              </div>
            </div>

            {/* Recommendations Loop */}
            <div className="space-y-6 text-left">
              <h2 className="text-lg font-bold text-white flex items-center gap-2">
                <FaBrain className="text-brand-green" />
                <span>Interventions for {species.commonName} ({species.scientificName})</span>
              </h2>

              <div className="grid grid-cols-1 gap-6">
                {species.recommendations.map((rec, index) => (
                  <Card
                    key={index}
                    hoverable
                    className="border-emerald-900/10 p-5 flex flex-col justify-between"
                  >
                    <div className="space-y-4">
                      {/* Priority Tag & Number */}
                      <div className="flex justify-between items-center">
                        <span className={`text-[9px] font-bold px-2 py-0.5 rounded-md uppercase border ${
                          rec.priority === 'HIGH' ? 'bg-red-950/60 text-red-400 border-red-900/30' :
                          rec.priority === 'MEDIUM' ? 'bg-amber-950/60 text-amber-400 border-amber-900/30' :
                          'bg-emerald-950/60 text-emerald-400 border-emerald-900/30'
                        }`}>
                          Priority: {rec.priority}
                        </span>
                        <span className="text-xs font-mono text-gray-500">ID: AI-REC-{index + 1}</span>
                      </div>

                      {/* Title */}
                      <h3 className="text-base font-extrabold text-white leading-tight">
                        {rec.title}
                      </h3>

                      {/* Reasoning */}
                      <div className="text-xs leading-relaxed space-y-2">
                        <p className="text-gray-400">
                          <strong className="text-white block font-semibold mb-0.5">Rationale:</strong>
                          {rec.reason}
                        </p>
                        
                        {/* Supporting data */}
                        <div className="flex items-center space-x-2 text-[10px] text-brand-green bg-green-50/5 border border-green-950/30 p-2.5 rounded-lg w-fit">
                          <FaChartLine />
                          <span>Supporting Telemetry: <strong>{rec.supportingData}</strong></span>
                        </div>
                      </div>
                    </div>
                  </Card>
                ))}
              </div>
            </div>

          </div>

        </div>

      </div>
    </DashboardLayout>
  );
};
export default Recommendations;
